writeFileSync(path.join(ROOT, '.gitignore'), GITIGNORE, 'utf8');
console.log('.gitignore written');

for (const manifest of ['package.json', 'server/package.json', 'web/package.json', 'desktop/package.json']) {
  const file = path.join(ROOT, manifest);
  const json = JSON.parse(readFileSync(file, 'utf8'));
  json.license = 'Apache-2.0';
  json.author = json.author && json.author !== 'WooSSH Explorer' ? json.author : HOLDER;
  writeFileSync(file, `${JSON.stringify(json, null, 2)}\n`, 'utf8');
  console.log(`  ${manifest}: license=Apache-2.0`);
}

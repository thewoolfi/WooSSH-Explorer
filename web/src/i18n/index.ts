const DICTIONARIES: Record<Locale, Dictionary> = { en, ru };

/** Plural forms, keyed by message key. Russian needs three, English one. */
const PLURALS: Partial<Record<MessageKey, Record<Locale, PluralForms>>> = {
  'status.selected': {
    en: { one: '{count} selected', other: '{count} selected' },
    ru: { one: 'Выбран {count}', few: 'Выбрано {count}', many: 'Выбрано {count}', other: 'Выбрано {count}' },
  },
  'inspector.selectedCount': {
    en: { one: '{count} item selected', other: '{count} items selected' },
    ru: {
      one: 'Выбран {count} объект',
      few: 'Выбрано {count} объекта',
      many: 'Выбрано {count} объектов',
      other: 'Выбрано {count} объектов',
    },
  },
};

export const LOCALES: { value: Locale; label: string }[] = [
  { value: 'en', label: 'English' },
  { value: 'ru', label: 'Русский' },
];

let current: Locale = detectLocale();
const listeners = new Set<() => void>();

/** Russian when the OS or the browser asks for it, English otherwise. */
function detectLocale(): Locale {
  const candidates = [
    typeof navigator === 'undefined' ? '' : navigator.language,
    ...(typeof navigator === 'undefined' ? [] : (navigator.languages ?? [])),
  ];
  return candidates.some((tag) => typeof tag === 'string' && tag.toLowerCase().startsWith('ru')) ? 'ru' : 'en';
}

export function getLocale(): Locale {
  return current;
}

export function setLocale(locale: Locale): void {
  if (locale === current) return;
  current = locale;
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
  try {
    window.localStorage.setItem('ssh-explorer.locale', locale);
  } catch {
    /* private mode */
  }
  for (const listener of listeners) listener();
}

/** Restores the stored choice once, at startup. */
export function initLocale(): void {
  try {
    const stored = window.localStorage.getItem('ssh-explorer.locale');
    if (stored === 'en' || stored === 'ru') current = stored;
  } catch {
    /* private mode */
  }
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export type TranslateParams = Record<string, string | number>;

/** Translates a key. A missing key returns the key itself — never an empty label. */
export function translate(key: MessageKey, params?: TranslateParams): string {
  const template = DICTIONARIES[current][key] ?? en[key] ?? key;
  return params ? interpolate(template, params) : template;
}

/** Plural-aware variant for keys registered in {@link PLURALS}. */
export function translateCount(key: MessageKey, count: number, params?: TranslateParams): string {
  const forms = PLURALS[key]?.[current];
  if (!forms) return translate(key, { count, ...params });
  const category = pluralCategory(current, count);
  const template = forms[category] ?? forms.other;
  return interpolate(template, { count, ...params });
}

function pluralCategory(locale: Locale, count: number): keyof PluralForms {
  try {
    return new Intl.PluralRules(locale).select(count) as keyof PluralForms;
  } catch {
    return count === 1 ? 'one' : 'other';
  }
}

function interpolate(template: string, params: TranslateParams): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

